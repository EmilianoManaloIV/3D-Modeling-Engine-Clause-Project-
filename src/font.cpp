void buildAtlas(std::vector<uint8_t>& px) {
    px.assign(size_t(kAtlasW) * kAtlasH, 0);
    for (int g = 0; g < 95; ++g) {
        int ox = (g % kCols) * kCellW, oy = (g / kCols) * kCellH;
        const char* const* rows = kGlyphs[g];
        int rowCount = 7;
        for (const Descender& d : kDescenders)
            if (d.c == char(32 + g)) {
                rows = d.rows;
                rowCount = 9;
            }
        for (int y = 0; y < rowCount; ++y)
            for (int x = 0; x < kGlyphW; ++x)
                if (rows[y][x] == '#') px[size_t(oy + y) * kAtlasW + ox + x] = 255;
    }
    for (int y = kWhiteY - 4; y < kWhiteY + 4; ++y)
        for (int x = kWhiteX - 4; x < kWhiteX + 4; ++x) px[size_t(y) * kAtlasW + x] = 255;
}
